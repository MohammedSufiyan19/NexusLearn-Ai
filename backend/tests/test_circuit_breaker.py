"""
Tests for LLM Resilience & Circuit Breaker (Phase 6).
Verifies:
  - CircuitBreaker state transitions (CLOSED -> OPEN -> HALF_OPEN -> CLOSED)
  - Failure threshold counting
  - Cooldown timer
  - Simulated primary provider failure falls back cleanly to Mistral
"""
from unittest.mock import MagicMock, patch

from app.llm.providers import CBState, CircuitBreaker, invoke_llm


def test_circuit_breaker_transitions():
    """Circuit breaker opens after threshold failures, then half-opens after cooldown."""
    cb = CircuitBreaker(failure_threshold=3, recovery_timeout=0.1)
    assert cb.state == CBState.CLOSED

    # 1 failure -> still CLOSED
    cb.record_failure()
    assert cb.state == CBState.CLOSED

    # 2 failures -> still CLOSED
    cb.record_failure()
    assert cb.state == CBState.CLOSED

    # 3 failures -> trips to OPEN
    cb.record_failure()
    assert cb.state == CBState.OPEN

    # Wait for recovery timeout
    import time
    time.sleep(0.15)

    # State becomes HALF_OPEN
    assert cb.state == CBState.HALF_OPEN

    # Success in HALF_OPEN resets to CLOSED
    cb.record_success()
    assert cb.state == CBState.CLOSED


def test_fallback_routing_on_primary_failure():
    """
    Test Case TC5 from roadmap:
    Simulated 429 / failure from primary (Groq) routes to fallback (Mistral).
    """
    mock_mistral_response = MagicMock()
    mock_mistral_response.content = "Answer generated by Mistral fallback."

    with patch("app.llm.providers._make_groq") as mock_groq_factory, \
         patch("app.llm.providers._make_mistral") as mock_mistral_factory, \
         patch("app.llm.providers.settings") as mock_settings:

        mock_settings.groq_api_key = "test-groq-key"
        mock_settings.mistral_api_key = "test-mistral-key"

        mock_groq = MagicMock()
        mock_groq.invoke.side_effect = Exception("Rate limit exceeded 429 Too Many Requests")
        mock_groq_factory.return_value = mock_groq

        mock_mistral = MagicMock()
        mock_mistral.invoke.return_value = mock_mistral_response
        mock_mistral_factory.return_value = mock_mistral

        provider_log = []
        ans = invoke_llm("Explain relational algebra", provider_log=provider_log)

        assert ans == "Answer generated by Mistral fallback."
        assert "mistral" in provider_log
